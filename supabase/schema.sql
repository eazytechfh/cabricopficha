add column if not exists uf text;

alter table public.fichas_venda enable row level security;

drop policy if exists "service role can manage fichas_venda" on public.fichas_venda;

create policy "service role can manage fichas_venda"
on public.fichas_venda
as permissive
for all
to service_role
using (true)
with check (true);

create extension if not exists pgcrypto;

create table if not exists public.access_codes (
  id uuid primary key default gen_random_uuid(),
  nome_responsavel text not null,
  codigo_acesso text not null unique,
  nivel_acesso text not null check (nivel_acesso in ('admin', 'consultor', 'andamento')),
  ativo boolean not null default true,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create table if not exists public.document_templates (
  key text primary key,
  content text not null,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create table if not exists public.activity_logs (
  id uuid primary key default gen_random_uuid(),
  entity_type text not null check (entity_type in ('ficha', 'document_template')),
  entity_id text not null,
  entity_label text not null,
  action text not null,
  summary text not null,
  actor_id text not null,
  actor_name text not null,
  details jsonb not null default '[]'::jsonb,
  created_at timestamptz not null default now()
);

