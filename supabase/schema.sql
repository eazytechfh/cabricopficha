  municipio text,
  uf text,
  cpf_cnpj text,
  cpf_normalizado text,
  cnh text,
  data_nascimento date,
  data_primeira_cnh date,
  nacionalidade text,
  estado_civil text,
  profissao text,
  email text,
  nome_consultor text,
  origem text,
  sne text,
  forma_pagamento text,
  banco text,
  valor_total numeric(12, 2),
  valor_entrada numeric(12, 2),
  valor_restante numeric(12, 2),
  observacao_valor_restante text,
  clausula_adicional text,
  instancia_processo text,
